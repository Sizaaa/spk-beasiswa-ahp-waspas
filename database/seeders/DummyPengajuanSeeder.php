                    ]);
                }

                // 2. Buat atau perbarui pengajuan beasiswa
                $waktu = now();
                DB::table('pengajuan_beasiswa')->updateOrInsert(
                    ['akun_id' => $akunId],
                    [
                        'nama_lengkap' => $item['nama'],
                        'nisn' => $item['nisn'],
                        'asal_sekolah' => $item['sekolah'],
                        'kelas' => $item['kelas'],
                        'nomor_hp' => $item['hp'],
                        'alamat_lengkap' => $item['alamat'],
                        'pekerjaan_orang_tua' => $item['pekerjaan'],
                        'penghasilan_orang_tua' => $item['penghasilan'],
                        'jumlah_tanggungan' => $item['tanggungan'],
                        'kondisi_tempat_tinggal' => $item['kondisi'],
                        'nilai_akademik' => $item['akademik'],
                        'prestasi_non_akademik' => $item['prestasi'],
                        'status' => $item['status'],
                        'catatan_admin' => $item['catatan'],
                        'diajukan_pada' => $waktu->copy()->subDays(rand(1, 14)),
                        'created_at' => $waktu->copy()->subDays(15),
                        'updated_at' => $waktu,
                    ]
                );

                // 3. Siapkan berkas fisik dummy (KK, Slip Penghasilan, Rapor, Sertifikat)
                $folderAkun = $baseFolder.DIRECTORY_SEPARATOR.'akun_'.$akunId;
                if (! is_dir($folderAkun)) {
                    @mkdir($folderAkun, 0755, true);
                }

                if (is_dir($folderAkun)) {
                    foreach (['kk.pdf', 'penghasilan.pdf', 'rapor.pdf', 'sertifikat.pdf'] as $berkas) {
                        $target = $folderAkun.DIRECTORY_SEPARATOR.$berkas;
                        if (! file_exists($target)) {
                            @file_put_contents($target, $minimalPdf);
                        }
                    }
                }
            });
        }
    }
